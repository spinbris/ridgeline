"""Synthetic-road project binding - ROAD-01, project #2.

The **Kestrel Highway Upgrade**: a 7.2 km brownfield highway upgrade with one viaduct and one
bridge, business-case phase, $68.4M base estimate (Director ruling 07/09/2026, brief §5.4). Its
register and `.xer` are generated by `scripts/build_synthetic_road_fixture.py` under
`tests/fixtures/synthetic_road/`.

**This module is data only**, which is the point of the exercise. GENERIC-01 removed the
active-management allowlist that refused any project it had not been taught by name, so a third
project is now a binding module plus its data and no engine change at all - and this file is the
first evidence that the claim is true rather than merely asserted.

`headless_config` is deliberately absent: this project never runs the legacy `--no-excel` cost
path, and supplying values nothing asks for would put cost-group coefficients and bucket variances
on the record that no one elicited. Leaving it out keeps the fail-loud behaviour where it still has
something to catch.
"""
