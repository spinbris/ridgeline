"""Build the minimal schedule on which a CPM replay differs from an additive sum.

SHOWCASE-02 D-1(c), signed 19/09/2026.

WHY THIS FIXTURE EXISTS
    S-3 measured the replay-vs-additive gap on both shipped projects at 100,000
    iterations and found it **exactly zero**, on every iteration (brief §2.6). The cause
    is not the schedules: all 20 drivers across the two projects carry
    ``injection_method=discrete_event_additive_days`` **and** a gating activity with zero
    total float, so every sampled delay is fired at a critical gate and reaches the finish
    undiminished. Summing is then the same arithmetic the CPM performs.

    So neither shipped fixture can demonstrate the commissioned property, and the Director
    ruled D-1(c): a purpose-built minimal schedule, which touches no shipped project's
    inputs and therefore moves no golden.

THE TOPOLOGY, AND WHY IT IS THESE NUMBERS
    Two parallel paths between a common start and finish::

        START(0h) --> CRIT(400h)  --> END(0h)
        START(0h) --> FLOAT(80h)  --> END(0h)

    Project finish is 400 h (50 working days at 8 h/day), set by CRIT. FLOAT carries
    400 - 80 = **320 h (40 days)** of total float.

    Two risks, one gating each path. Both draw the same PERT in days (5 / 10 / 20), so the
    largest possible delay is 20 days = 160 h - deliberately **less than half** FLOAT's
    320 h of float. The floated risk therefore contributes **exactly zero** to the project
    finish on every iteration in which it fires, while contributing its full draw to an
    additive sum. The gap is not statistical; it is the whole of that risk's draw, always.

    Chosen so the demonstration is hand-checkable and cannot become flaky: no iteration
    count, seed or tail behaviour can make a 160 h delay consume 320 h of float.

WHY TT_Task THROUGHOUT AND ONLY FS LINKS
    Milestones and non-FS logic are XERREAL-01's business, not this brief's, and adding
    them here would change what the fixture is for. A zero-duration TT_Task serves as the
    convergence node identically for the CPM. The authored ``total_float_hr_cnt`` column
    is set consistently with the topology: the kernel computes its own slack
    (``cpm_kernel.compute_slack``) and never reads that column, but the auto-mapper's
    Filter B does, and a fixture whose authored float contradicts its own shape would be
    a lie waiting to mislead a selector.

REGENERATING
    python scripts/build_float_absorption_fixture.py

    Snapshot fixtures are regenerated by script and never hand-edited.
"""
from __future__ import annotations

import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

OUT_DIR = REPO_ROOT / "tests" / "fixtures" / "float_absorption"
OUT_XER = OUT_DIR / "float_absorption_schedule.xer"

#: Working hours per day. Every duration below is a whole number of these.
HOURS_PER_DAY = 8.0

#: The long path's duration, which sets the project finish.
CRIT_HOURS = 400.0
#: The short parallel path. Its float is CRIT_HOURS - FLOAT_HOURS.
FLOAT_HOURS = 80.0
#: Derived, and asserted below rather than trusted.
EXPECTED_FLOAT_HOURS = CRIT_HOURS - FLOAT_HOURS  # 320.0


def build_tables() -> dict:
    import pandas as pd

    calendar = [{
        "clndr_id": 1, "clndr_name": "Standard 5-day", "default_flag": "Y",
        "clndr_data": "(0||CalendarData())", "day_hr_cnt": HOURS_PER_DAY,
        "week_hr_cnt": 40.0, "month_hr_cnt": 172.0, "year_hr_cnt": 2000.0,
    }]
    projwbs = [{
        "wbs_id": 900, "proj_id": 1, "parent_wbs_id": None,
        "wbs_short_name": "FA", "wbs_name": "Float absorption demonstrator",
        "seq_num": 1,
    }]

    start = pd.Timestamp("2026-07-06 08:00")
    task: list[dict] = []
    taskpred: list[dict] = []

    def add_task(tid: int, code: str, name: str, hrs: float, float_h: float) -> int:
        end = start + pd.Timedelta(hours=hrs)
        task.append({
            "task_id": tid, "proj_id": 1, "wbs_id": 900, "clndr_id": 1,
            "task_code": code, "task_name": name, "task_type": "TT_Task",
            "target_drtn_hr_cnt": float(hrs),
            "total_float_hr_cnt": float(float_h),
            "free_float_hr_cnt": float(min(float_h, 40.0)),
            "early_start_date": start, "early_end_date": end,
            "late_start_date": start, "late_end_date": end,
            "target_start_date": start, "target_end_date": end,
            "cstr_date": None, "cstr_type": "",
            "driving_path_flag": "Y" if float_h == 0.0 else "N",
        })
        return tid

    def link(pred_tid: int, succ_tid: int, pred_id: int) -> None:
        taskpred.append({
            "task_pred_id": pred_id, "task_id": succ_tid,
            "pred_task_id": pred_tid, "pred_type": "PR_FS", "lag_hr_cnt": 0.0,
        })

    t_start = add_task(9001, "FA.START", "Site establishment complete", 0.0, 0.0)
    t_crit = add_task(9002, "FA.CRIT", "Controlling works (drives the finish)",
                      CRIT_HOURS, 0.0)
    t_float = add_task(9003, "FA.FLOAT", "Parallel works (carries float)",
                       FLOAT_HOURS, EXPECTED_FLOAT_HOURS)
    t_end = add_task(9004, "FA.END", "Practical completion", 0.0, 0.0)

    link(t_start, t_crit, 9501)
    link(t_start, t_float, 9502)
    link(t_crit, t_end, 9503)
    link(t_float, t_end, 9504)

    return {"CALENDAR": calendar, "PROJWBS": projwbs,
            "TASK": task, "TASKPRED": taskpred}


def main() -> int:
    from src.sra.cpm.graph_builder import build_schedule_graph
    from src.sra.cpm.xer_reader import parse_xer
    from src.sra.cpm.xer_writer import write_xer

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    write_xer(build_tables(), OUT_XER)

    # The output must be LF, or `git ls-files --eol | grep w/crlf` lists it at close.
    # `xer_writer` wrote CRLF on Windows until this brief fixed it (write_text ->
    # write_bytes); this asserts rather than re-normalises, so a regression in the writer
    # fails here loudly instead of being papered over by every builder in turn.
    assert b"\r\n" not in OUT_XER.read_bytes(), (
        f"{OUT_XER.name} came back with CRLF - xer_writer has regressed to write_text")

    # Re-read through the real path and assert the shape this fixture promises, so a
    # regeneration that silently changed the topology fails here rather than in the test
    # that depends on it.
    graph = build_schedule_graph(parse_xer(str(OUT_XER)))
    acts = {a.code: a for a in graph.activities.values()}
    assert set(acts) == {"FA.START", "FA.CRIT", "FA.FLOAT", "FA.END"}, sorted(acts)
    assert acts["FA.CRIT"].total_float_hours == 0.0, acts["FA.CRIT"].total_float_hours
    assert acts["FA.FLOAT"].total_float_hours == EXPECTED_FLOAT_HOURS, (
        acts["FA.FLOAT"].total_float_hours)
    assert len(graph.links) == 4, len(graph.links)

    print(f"wrote {OUT_XER.relative_to(REPO_ROOT)}: "
          f"{len(graph.activities)} activities, {len(graph.links)} links; "
          f"FA.CRIT float 0 h, FA.FLOAT float {EXPECTED_FLOAT_HOURS:.0f} h "
          f"({EXPECTED_FLOAT_HOURS / HOURS_PER_DAY:.0f} days)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
