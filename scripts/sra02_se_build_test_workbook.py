"""Build the SRA-02 S-E reconciliation test workbook.

Regenerates ``tests/fixtures/sra02_se/se_cross_check_register.xlsx``: a scaffolded
register carrying a handful of synthetic schedule risks, recalculated once in Excel
so the ``Summary`` comparator formulas carry cached values.

Per the test discipline, fixtures are regenerated by script and never
hand-edited. Run this, then update ``FIXTURE_SHA256`` in
``tests/test_sra02_se_reconciliation.py`` with the hash printed at the end.

    .venv/Scripts/python.exe scripts/sra02_se_build_test_workbook.py

Requires Excel (xlwings COM) - it is the only way in this repo to put cached
formula values into a workbook, and the reason the artefact is committed rather
than built at test time: the reconciliation gate must run on machines and CI
runners without Excel.

**Why this script asserts a cell count.** The repo's other Excel recalc
(``src/sra/strawman_reader.py:861-875``) wraps the whole COM sequence in
``except Exception`` and records failure in a returned dict field. A recalc that
silently did nothing would leave the four Summary cells at ``None``, the
reconciliation would read nil on both sides, and the gate would pass having
compared nothing - NOOPCHECK-01 shape 4, a check that succeeds while writing
nothing. So the recalc here is verified by counting the cells that actually came
back numeric, and the script fails loudly if that count is not four.
"""
from __future__ import annotations

import hashlib
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

from openpyxl import load_workbook  # noqa: E402

from tools.register_scaffold import (  # noqa: E402
    CALIBRATION_LABELS,
    CALIBRATION_SHEET,
    DAY_RATE_NAME,
    HEADER_ROW,
    RISK_REGISTER_SHEET,
    build_template,
)

OUT_PATH = REPO_ROOT / "tests" / "fixtures" / "sra02_se" / "se_cross_check_register.xlsx"

#: Synthetic, non-round day rate - a wrong day-rate source shows up as a wrong
#: dollar figure rather than coinciding with a default.
DAY_RATE = 17500.0

#: (risk_id, status, time_impact, mode, prob_time, opt, ml, pess).
#: Deliberately mixed: every Mode the grid defines appears, including Parallel
#: (which contributes zero to Comparator 2 and non-zero to Comparator 1), and one
#: Time=No row carrying full schedule numbers that BOTH sides must exclude.
SYNTHETIC_ROWS = [
    ("RSK001", "Open", "Yes", "Series", 0.45, 5.0, 12.0, 24.0),
    ("RSK002", "Open", "Yes", "Hybrid", 0.50, 3.0, 7.0, 16.0),
    ("RSK003", "Open", "Yes", "Parallel", 0.35, 1.0, 4.0, 10.0),
    ("RSK004", "Open", "Yes", "Series", 0.30, 6.0, 15.0, 35.0),
    ("RSK005", "Open", "Yes", "Hybrid", 0.40, 2.0, 6.0, 14.0),
    ("RSK006", "Open", "No", "Series", 0.60, 4.0, 9.0, 19.0),
]

_HEADERS = {
    "risk_id": "Risk ID",
    "status": "Risk Status",
    "time_impact": "Time Impact",
    "mode": "Mode",
    "prob": "Probability",
    "prob_time": "Probability (Time)",
    "opt": "Optimistic (days)",
    "ml": "Most Likely (days)",
    "pess": "Pessimistic (days)",
}


def _column_map(ws) -> dict[str, int]:
    """Header-driven lookup, never positional."""
    found: dict[str, int] = {}
    for col in range(1, ws.max_column + 1):
        value = ws.cell(row=HEADER_ROW, column=col).value
        for key, header in _HEADERS.items():
            if value == header and key not in found:
                found[key] = col
    missing = sorted(set(_HEADERS) - set(found))
    if missing:
        raise SystemExit(f"header(s) not found on {ws.title!r} row {HEADER_ROW}: {missing}")
    return found


def _day_rate_cell(wb) -> tuple[str, str]:
    """Resolve the MC_day_rate named range rather than assuming its address."""
    if DAY_RATE_NAME not in wb.defined_names:
        raise SystemExit(f"named range {DAY_RATE_NAME!r} not defined on the template")
    destinations = list(wb.defined_names[DAY_RATE_NAME].destinations)
    if len(destinations) != 1:
        raise SystemExit(f"{DAY_RATE_NAME} resolved to {len(destinations)} destinations")
    return destinations[0]


def populate(path: Path) -> None:
    wb = load_workbook(path)
    try:
        ws = wb[RISK_REGISTER_SHEET]
        col = _column_map(ws)
        for offset, row_values in enumerate(SYNTHETIC_ROWS):
            r = HEADER_ROW + 1 + offset
            for key, value in zip(
                ("risk_id", "status", "time_impact", "mode",
                 "prob_time", "opt", "ml", "pess"),
                row_values,
            ):
                ws.cell(row=r, column=col[key], value=value)
            # SPEC R-10 (METHFIRE-01): these are schedule-only risks, and a risk's one
            # probability is `Probability` whatever it costs. `Probability (Time)` carries the
            # same value until PROBTIME-01 removes it; the reader refuses a difference.
            ws.cell(row=r, column=col["prob"], value=row_values[4])
        sheet, addr = _day_rate_cell(wb)
        wb[sheet][addr] = DAY_RATE
    finally:
        wb.save(path)
        wb.close()


def recalc_in_excel(path: Path) -> None:
    """Open in Excel, force a full rebuild, save. Verified by cell count, not rc."""
    import xlwings as xw

    app = xw.App(visible=False)
    try:
        book = app.books.open(str(path))
        try:
            app.api.CalculateFullRebuild()
            book.save()
        finally:
            book.close()
    finally:
        app.quit()


#: What identity-bearing docProps fields are set to. Empty matches the repo's one
#: already-clean committed register, `tests/fixtures/synthetic_wind/wind_register.xlsx`
#: (openpyxl-only, never Excel-saved), so "clean" means one thing across both.
NEUTRAL = ""

#: `docProps/core.xml` fields that carry a person or an organisation.
_CORE_IDENTITY_TAGS = ("dc:creator", "cp:lastModifiedBy")

#: `docProps/app.xml` fields that carry an organisation or a machine path. None are
#: present on the workbook Excel writes today; they are handled so that a future
#: Excel version which does stamp one cannot reintroduce the class silently.
_APP_IDENTITY_TAGS = ("Company", "Manager", "HyperlinkBase")

#: The third member, and the one C-1 found: Excel records the workbook's own
#: directory here as `x15ac:absPath`, inside an `mc:AlternateContent` block it
#: writes for no other purpose. On Windows that path names the account.
_WORKBOOK_MEMBER = "xl/workbook.xml"


def strip_identity_metadata(path: Path) -> dict[str, str]:
    """Blank the identity-bearing docProps fields by **zip-member rewrite**.

    Excel stamps the signed-in user into `cp:lastModifiedBy` on every save, so a
    workbook that has been through `recalc_in_excel` carries a real person's name.
    This fixture is committed and its sha256 is pinned by a test, which would make
    that name a recorded identity - GOLDINPUT-USERNAME-01's class.

    **Rewrites the zip members, never an openpyxl round-trip.** openpyxl cannot
    round-trip a workbook carrying cached formula values: it re-serialises the
    formulas and drops the cached results, taking the four Summary cells from
    4/4 back to 0/4. The reader then nils by contract, the reconciliation compares
    nothing to nothing, and the gate passes vacuously - NOOPCHECK-01 shape 4, the
    exact shape the cached-cell count exists to prevent. So this rewrites two XML
    members in place and leaves every other byte-stream member untouched.

    Returns the before-values, for the record.
    """
    import re
    import shutil
    import tempfile
    import zipfile

    found: dict[str, str] = {}

    def _blank(xml: str, tags: tuple[str, ...]) -> str:
        for tag in tags:
            pattern = f"<{tag}>(.*?)</{tag}>"
            match = re.search(pattern, xml, re.S)
            if match:
                found[tag] = match.group(1)
                xml = re.sub(pattern, f"<{tag}>{NEUTRAL}</{tag}>", xml, count=1, flags=re.S)
        return xml

    def _drop_abs_path(xml: str) -> str:
        """Remove the build directory Excel records in ``xl/workbook.xml``.

        Excel wraps ``x15ac:absPath`` in an ``mc:AlternateContent`` block written
        for that one purpose, so the whole block goes: leaving an empty
        ``mc:Choice`` behind would be valid but pointless. If a future Excel puts
        the attribute somewhere else, the second pass removes the bare element and
        the sweep in :func:`identity_offenders` still fails if anything survives.
        """
        block = re.compile(r"<mc:AlternateContent\b[^>]*>.*?</mc:AlternateContent>", re.S)
        for match in block.finditer(xml):
            if "absPath" in match.group(0):
                url = re.search(r'absPath[^>]*?url="([^"]*)"', match.group(0))
                found["x15ac:absPath"] = url.group(1) if url else match.group(0)
                xml = xml.replace(match.group(0), "", 1)
        bare = re.compile(r"<[A-Za-z0-9]+:?absPath\b[^>]*/>", re.I)
        match = bare.search(xml)
        if match:
            found.setdefault("x15ac:absPath", match.group(0))
            xml = bare.sub("", xml)
        return xml

    tmp_dir = Path(tempfile.mkdtemp())
    tmp_path = tmp_dir / path.name
    with zipfile.ZipFile(path) as src, zipfile.ZipFile(
        tmp_path, "w", zipfile.ZIP_DEFLATED
    ) as dst:
        for item in src.infolist():
            data = src.read(item.filename)
            if item.filename == "docProps/core.xml":
                data = _blank(data.decode("utf-8"), _CORE_IDENTITY_TAGS).encode("utf-8")
            elif item.filename == "docProps/app.xml":
                data = _blank(data.decode("utf-8"), _APP_IDENTITY_TAGS).encode("utf-8")
            elif item.filename == _WORKBOOK_MEMBER:
                data = _drop_abs_path(data.decode("utf-8")).encode("utf-8")
            # Carry the original ZipInfo so member order, timestamps and compression
            # follow the source rather than "now" - the rebuild stays reproducible.
            dst.writestr(item, data)
    shutil.copyfile(tmp_path, path)
    shutil.rmtree(tmp_dir, ignore_errors=True)
    return found


def identity_metadata(path: Path) -> dict[str, str]:
    """Read back the fields :func:`strip_identity_metadata` writes. Used by the
    script to prove the strip landed, and by the test to prove it stayed."""
    import re
    import zipfile

    out: dict[str, str] = {}
    with zipfile.ZipFile(path) as z:
        for member, tags in (("docProps/core.xml", _CORE_IDENTITY_TAGS),
                             ("docProps/app.xml", _APP_IDENTITY_TAGS)):
            if member not in z.namelist():
                continue
            xml = z.read(member).decode("utf-8")
            for tag in tags:
                match = re.search(f"<{tag}>(.*?)</{tag}>", xml, re.S)
                if match:
                    out[tag] = match.group(1)
    return out


def identity_offenders(path: Path) -> dict[str, list[str]]:
    """Sweep **every** zip member for anything naming the person or the machine.

    :func:`identity_metadata` reads two docProps members by tag. That is narrower
    than the class it is named for: Excel also writes the workbook's own directory
    into ``xl/workbook.xml`` as ``x15ac:absPath``, which on Windows contains the
    account name. The C-1 finding is that a workbook can pass the docProps check
    and still name its author. So this reads the bytes of every member instead of
    trusting a field list.

    Three rules, none of which puts an identity literal in the repo:

    * ``absPath`` - the attribute itself, whatever it points at. A build path is
      machine identity even when it carries no account name.
    * a user-profile path (``<drive>:\\Users\\``) anywhere in any member.
    * the **current** login name, resolved at call time by :func:`getpass.getuser`.
      Deliberately not a constant: the check has to be about whoever ran the build,
      not about one recorded person, and a literal here would reintroduce exactly
      the thing being removed.

    ``getpass.getuser`` is left unguarded on purpose. If it cannot resolve a name
    it raises, and this errors loudly rather than dropping a rule and passing -
    a silently-skipped rule is the false green this whole check exists to close.
    The residual cost is that a pathologically short login name would match broadly
    and red the lane; that failure is loud and diagnosable, which is the direction
    to fail in.

    Returns ``{member: [rule names that fired]}``, empty when clean.
    """
    import getpass
    import re
    import zipfile

    rules: list[tuple[str, "re.Pattern[bytes]"]] = [
        ("absPath attribute", re.compile(rb"absPath", re.I)),
        ("user-profile path", re.compile(rb"[A-Za-z]:\\Users\\", re.I)),
        ("login name", re.compile(re.escape(getpass.getuser().encode()), re.I)),
    ]

    offenders: dict[str, list[str]] = {}
    with zipfile.ZipFile(path) as z:
        for member in z.namelist():
            data = z.read(member)
            fired = [name for name, pattern in rules if pattern.search(data)]
            if fired:
                offenders[member] = fired
    return offenders


def cached_summary_values(path: Path) -> dict[str, object]:
    wb = load_workbook(path, data_only=True)
    try:
        ws = wb[CALIBRATION_SHEET]
        return {
            label: ws.cell(row=r, column=2).value
            for r, label in enumerate(CALIBRATION_LABELS, start=1)
        }
    finally:
        wb.close()


def main() -> int:
    OUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    build_template(OUT_PATH, prefix="RSK")
    populate(OUT_PATH)

    before = cached_summary_values(OUT_PATH)
    numeric_before = [v for v in before.values() if isinstance(v, (int, float))]
    print(f"before recalc: {len(numeric_before)}/4 Summary cells carry a cached value")

    recalc_in_excel(OUT_PATH)

    # Excel stamps the signed-in user on save, so the strip runs AFTER the recalc.
    # It also runs BEFORE the cached-cell count below, so that count guards the
    # artefact that actually ships rather than a pre-strip one - the guard has to
    # sit on the far side of the last step that could destroy what it checks.
    stripped = strip_identity_metadata(OUT_PATH)
    print(f"stripped identity metadata: { {k: '<redacted>' for k in stripped} }")
    remaining = {k: v for k, v in identity_metadata(OUT_PATH).items() if v != NEUTRAL}
    if remaining:
        raise SystemExit(
            f"identity fields survived the strip: {sorted(remaining)}. The fixture "
            f"must not be committed."
        )
    print("identity fields read back neutral after strip: OK")

    # C-1: the field list above is narrower than the class, so the whole archive is
    # swept as well. Same side of the strip, same refusal.
    import zipfile

    with zipfile.ZipFile(OUT_PATH) as _z:
        swept = len(_z.namelist())
    survivors = identity_offenders(OUT_PATH)
    if survivors:
        raise SystemExit(
            f"zip members still name the machine or the person: "
            f"{ {m: sorted(r) for m, r in sorted(survivors.items())} }. The fixture "
            f"must not be committed."
        )
    print(f"all {swept} zip members read back clean of build paths and login "
          f"name: OK")

    after = cached_summary_values(OUT_PATH)
    numeric_after = [v for v in after.values() if isinstance(v, (int, float))]
    for label, value in after.items():
        print(f"  {label:46s} {value!r}")
    if len(numeric_after) != len(CALIBRATION_LABELS):
        raise SystemExit(
            f"recalc wrote {len(numeric_after)} cached values, expected "
            f"{len(CALIBRATION_LABELS)}. The workbook is NOT usable as a "
            f"reconciliation fixture - a nil read on both sides would pass "
            f"vacuously. Got: {after}"
        )

    digest = hashlib.sha256(OUT_PATH.read_bytes()).hexdigest()
    print(f"\n{OUT_PATH.relative_to(REPO_ROOT).as_posix()}")
    print(f"  bytes  {OUT_PATH.stat().st_size}")
    print(f"  sha256 {digest}")
    print("\nUpdate FIXTURE_SHA256 in tests/test_sra02_se_reconciliation.py.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
