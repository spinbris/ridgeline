"""Write `dashboard/publish.json`: the projects the dashboard may ship.

The list is derived, never typed: it is `publishable_projects()`, which asks each shipped binding's
`publish` and `confidential` through `is_publishable`. The dashboard
copy (`dashboard/scripts/copy-data.js`) reads the committed file, which
`tests/test_dashgate01_publish_list.py` holds equal to this output. The deploy guard does not read
it: it asks the bindings through `publishable_projects()` itself.

    python scripts/release/write_publish_list.py           # write the file
    python scripts/release/write_publish_list.py --check   # exit 1 if the committed file differs

To publish a project, set `publish=True, confidential=False` on its binding and rerun this.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

from src.sra.cpm.bindings.registry import publishable_projects  # noqa: E402

PUBLISH_LIST = REPO_ROOT / "dashboard" / "publish.json"


def render() -> str:
    body = {
        "_": "Generated by scripts/release/write_publish_list.py from the project bindings. "
             "Do not edit by hand: set publish/confidential on the binding and rerun it.",
        "projects": publishable_projects(),
    }
    return json.dumps(body, indent=2) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true",
                        help="report whether the committed file matches, and write nothing")
    args = parser.parse_args(argv)
    wanted = render()
    current = PUBLISH_LIST.read_bytes().decode("utf-8") if PUBLISH_LIST.exists() else None
    if args.check:
        if current == wanted:
            print(f"{PUBLISH_LIST.name} matches the bindings.")
            return 0
        print(f"{PUBLISH_LIST.name} does not match the bindings; rerun without --check.",
              file=sys.stderr)
        return 1
    PUBLISH_LIST.write_bytes(wanted.encode("utf-8"))
    print(f"wrote {PUBLISH_LIST.relative_to(REPO_ROOT).as_posix()}: {json.loads(wanted)['projects']}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
