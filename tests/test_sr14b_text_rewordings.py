def test_ac5_no_stage25_references_in_d3_constants() -> None:
    """Each of the five Director-signed SR14b rewordings is the rendered
    text, no "Stage 2.5" leakage permitted in any of them."""
    for name in (
        "COVER_PAGE_CAVEAT_TEXT",
        "COST_ARM_NOTE",
        "DIVERSIFICATION_LINE",
        "FOOTER_TEMPLATE",
        "METHODOLOGY_SUMMARY_JOINT_SAMPLING",
    ):
        constant_text = getattr(stage3_beta_report, name)
        assert "Stage 2.5" not in constant_text, (
            f"stage3_beta_report.{name} contains 'Stage 2.5', "
            "violates AC5 zero-reference audit."
        )


