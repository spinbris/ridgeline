# --- coverage: every key a real compose emits has a written treatment -----------------------------

def unlabelled(paths: list[str]) -> list[str]:
    """Inventory paths that would reach the reader under a code name."""
    missing = []
    for p in paths:
        parent, key = p.rsplit("/", 1)
        if parent.endswith(("[]", "{}")):
            if is_code_name(key) and key not in contract.COLUMN_LABELS:
                missing.append(p)
        elif key not in contract.HTML_FIELDS:
            missing.append(p)
    return missing


@pytest.fixture(scope="module")
def inventory() -> dict:
    return json.loads(INVENTORY.read_text(encoding="utf-8"))


def test_every_composed_key_has_a_written_treatment(inventory):
    missing = unlabelled(inventory["paths"])
    assert not missing, ("these composed keys reach the client under their code names - give each "
                         "a treatment in presentation_contract.HTML_FIELDS or COLUMN_LABELS:\n  "
                         + "\n  ".join(missing))


def test_red_the_coverage_check_sees_a_missing_label(inventory, monkeypatch):
    fields = dict(contract.HTML_FIELDS)
    del fields["day_rate_dollars_per_workday"]
    monkeypatch.setattr(contract, "HTML_FIELDS", fields)
    assert "page8_audit_trail/day_rate_dollars_per_workday" in unlabelled(inventory["paths"])


