def test_every_basis_the_cross_validator_emits_is_written():
    src = (REPO / "src" / "final" / "cross_validator.py").read_text(encoding="utf-8")
    start = src.index('"schedule_top3_basis": (') + len('"schedule_top3_basis": (')
    emitted = re.findall(r'"([a-z0-9_]+)"', src[start:src.index("),", start)])
    assert emitted, "the basis literals moved; this test no longer reads them"
    missing = [v for v in emitted if v not in contract.VALUE_LABELS]
    assert not missing, f"an enum value reaches the reader as code: {missing}"


def test_the_notebook_displays_blocks_and_decides_nothing_itself():
    nb = json.loads((REPO / "final_runner.ipynb").read_text(encoding="utf-8"))
    source = "\n".join("".join(c["source"]) for c in nb["cells"] if c["cell_type"] == "code")
    assert "from src.final.html_blocks import blocks" in source
    assert '.replace("_", " ").capitalize()' not in source, (
        "the notebook builds labels from key names again (FW-20)")
    assert "render(section, section=key)" in source, "the pages lose their order"
