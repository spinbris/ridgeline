"""DELIVFIX-01 / FW-19, FW-20: the HTML body shows tables as tables, and writes its labels.

Leg 1 read the deliverable and found its driver rankings, convergence figures and audit trail as a
vertical stack of one-line paragraphs (FW-19), under labels that were the code's own key names -
"Register path display", "Day rate dollars per workday" (FW-20). Both came from one notebook
function no test could reach. Its decisions now live in ``src/final/html_blocks.py``, driven by the
presentation contract, and are tested here directly.

The label coverage test reads ``tests/fixtures/delivfix01_composed_keys.json`` - every key a real
compose puts inside a rendered section, regenerated by ``scripts/inventory_composed_keys.py`` and
held to the composer by the slow test in ``test_delivfix01_composed_keys_drift.py``.
"""
