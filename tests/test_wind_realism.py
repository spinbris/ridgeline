# ---------------------------------------------------------------------------
# Register shape + capex tie (decision 5)
# ---------------------------------------------------------------------------

def test_register_is_full_capex_tied_wind_set():
    import openpyxl

    from src.v5_register_reader import read_risks_v5

    risks = read_risks_v5(str(WIND_REGISTER))
    assert len(risks) == 35
    assert all(r.risk_id.startswith("WT-") for r in risks)
    # Six wind cost groups, all populated.
    cgs = {r.correlation_group for r in risks}
    assert cgs == {f"CG{n:02d}" for n in range(1, 7)}
    # Mixed distributions present.
    dists = {r.distribution.lower() for r in risks}
    assert {"pert", "triangular", "lognormal"} <= dists

    # Decision 5: TIC equals the Wind Farm Beta capex, and per-CG base values
    # sum to the same total.
    wb = openpyxl.load_workbook(str(WIND_REGISTER), data_only=True, read_only=True)
    labels = {}
    for row in wb["MC_Params"].iter_rows(min_row=1, max_row=200, min_col=2,
                                          max_col=3, values_only=True):
        if row[0] is not None:
            labels[str(row[0]).strip()] = row[1]
    wb.close()
    tic = next(v for k, v in labels.items() if k.startswith("TIC"))
    assert float(tic) == WIND_CAPEX_TOTAL
    capex_bases = [float(v) for k, v in labels.items() if k.endswith("capex base ($)")]
    assert len(capex_bases) == 6
    assert sum(capex_bases) == WIND_CAPEX_TOTAL


# ---------------------------------------------------------------------------
# Cost QRA realism — monotonic P-bands, proportionate headline
# ---------------------------------------------------------------------------

def test_cost_qra_headline_proportionate_to_capex():
    from src.config import ChainConfig, SimConfig
    from src.simulation import MonteCarloEngine
    from src.v5_register_reader import read_risks_v5

    risks = read_risks_v5(str(WIND_REGISTER))
    engine = MonteCarloEngine(
        SimConfig(n_iter=8000, seed=42), buckets=[], chains=ChainConfig(),
        risks=risks, corr_coefficients={f"CG{n:02d}": 0.5 for n in range(1, 14)},
        seed=42)
    total = np.asarray(engine.run().ev_costs).sum(axis=1)
    p50, p80, p90, p95 = np.percentile(total, [50, 80, 90, 95])
    # Monotonic, non-degenerate.
    assert 0 < p50 < p80 < p90 < p95
    # Proportionate to a ~$50M capex: a believable feasibility-stage QRA
    # contingency band (well clear of zero, well short of implausible).
    assert 0.03 <= p80 / WIND_CAPEX_TOTAL <= 0.25


