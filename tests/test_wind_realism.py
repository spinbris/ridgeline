# ---------------------------------------------------------------------------
# Stage 3 realism — each schedule risk binds exactly one gating activity
# ---------------------------------------------------------------------------

def test_stage3_binds_match_wind03_mapping():
    """WIND-03 (Director-approved, all ten rows): the auto-mapper binds each
    risk per the approved per-risk prefix mapping - five risks onto a BOUNDED
    work group (controlling activity + the ten per-turbine detail branches),
    five kept 1:1 on their gate. This supersedes the pre-WIND-03 uniform
    ``== 1`` lock. The guarantee under test is now "bounded per the approved
    mapping" (total 58), NOT "single activity" - but still NOT runaway
    whole-schedule over-binding.
    """
    from src.sra.cpm.auto_mapper import expand_auto_rules
    from src.sra.cpm.cpm_simulation import ScheduleMCConfig, run_schedule_mc
    from src.sra.cpm.graph_builder import build_schedule_graph
    from src.sra.cpm.risk_driver_schema import AutoMapperRule
    from src.sra.cpm.xer_reader import parse_xer
    from src.sra.strawman_reader import read_risk_scope

    graph = build_schedule_graph(parse_xer(str(WIND_XER)))
    scope = read_risk_scope(str(WIND_REGISTER))
    rules = {}
    for _, row in scope.iterrows():
        if str(row["time_impact"]).strip() != "Yes":
            continue
        gate = str(row["prefix_list"]).strip()
        rules[row["risk_id"]] = AutoMapperRule(
            risk_id=row["risk_id"], pattern_id=str(row["pattern_id"]),
            pattern_prefixes=(gate,), float_threshold_hours=480.0,
            injection_method="additive_pert_days",
            opt_pert=float(row["opt_days"]), ml_pert=float(row["ml_days"]),
            pess_pert=float(row["pess_days"]),
            probability=float(row["probability_time"]),
            mode=str(row["mode_aggregated"]))
    assert len(rules) == 10
    drivers = expand_auto_rules(rules, graph)
    # WIND-03 approved per-risk bind counts (5 multi-activity, 5 kept 1:1).
    expected = {
        "WT-001": 11, "WT-002": 1, "WT-008": 11, "WT-009": 1, "WT-020": 10,
        "WT-021": 1, "WT-026": 1, "WT-027": 1, "WT-031": 11, "WT-032": 10,
    }
    counts = {rid: len(d.affected_activity_ids) for rid, d in drivers.items()}
    assert counts == expected, f"bind counts {counts} != approved {expected}"
    assert sum(counts.values()) == 58
    # Bounded: no risk binds more than its work group (11), a far cry from
    # the ~171-activity whole-schedule over-binding WIND-03 §1 warns against.
    assert max(counts.values()) <= 11

    result = run_schedule_mc(
        graph=graph, risk_drivers=drivers,
        config=ScheduleMCConfig(n_iter=4000, batch_size=2000, seed=42, mode_multipliers=TEST_MODE_MULTIPLIERS))
    finish_days = np.asarray(result.project_finish_hours) / 8.0
    p50, p80, p95 = np.percentile(finish_days, [50, 80, 95])
    assert 0 < p50 <= p80 <= p95
    # Risk-driven spread is modest (additive PERT on gating activities), not the
    # runaway inflation whole-group binding would produce.
    assert (p95 - p50) < 0.5 * p50
