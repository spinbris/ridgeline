def test_cost_mc_produces_pbands():
    from src.config import ChainConfig, SimConfig
    from src.simulation import MonteCarloEngine
    from src.v5_register_reader import read_risks_v5

    risks = read_risks_v5(str(WIND_REGISTER))
    assert len(risks) == 35
    assert all(r.risk_id.startswith("WT-") for r in risks)

    cfg = SimConfig(n_iter=3000, seed=42)
    cg_coeffs = {f"CG{n:02d}": 0.5 for n in range(1, 14)}
    engine = MonteCarloEngine(
        cfg, buckets=[], chains=ChainConfig(), risks=risks,
        corr_coefficients=cg_coeffs, seed=42,
    )
    result = engine.run()
    l2 = np.asarray(result.ev_costs).sum(axis=1)
    p50, p80, p90 = np.percentile(l2, [50, 80, 90])
    assert p50 >= 0 and p80 > 0 and p90 >= p80
    assert np.isfinite([p50, p80, p90]).all()


def test_cascade_kernel_fires_on_wind_group():
    """The cascade kernel detects + processes the WT-CAS wind cascade group.

    (Register-driven cascade is not wired — read_risks_v5 ignores
    Cascade_Group — so cascade_group is set on the RiskInputs here to drive
    the kernel, proving it is project-agnostic.)
    """
    from src.config import ChainConfig
    from src.integrated.cascade_integrated import apply_cascade_groups_integrated
    from src.v5_register_reader import read_risks_v5

    risks = read_risks_v5(str(WIND_REGISTER))
    for r in risks:
        if r.risk_id in ("WT-016", "WT-017"):
            r.cascade_group = "WT-CAS"
            r.ml_days = 8.0  # give the group schedule slip to accumulate

    n_iter, n_risks = 200, len(risks)
    ev_costs = np.abs(np.random.default_rng(1).normal(2e5, 5e4, size=(n_iter, n_risks)))
    result = apply_cascade_groups_integrated(
        ev_costs=ev_costs, ev_days=None, risks=risks,
        risk_ids_dual=[], dual_lookup={},
        chain_config=ChainConfig(cascade_enabled=True),
        rng=np.random.default_rng(42),
    )
    assert result.n_groups >= 1
    assert "WT-CAS" in result.group_membership
    assert sorted(result.group_membership["WT-CAS"]) == [15, 16]  # WT-016, WT-017


