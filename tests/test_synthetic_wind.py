def test_stage3_cpm_produces_pbands():
    from src.sra.cpm.cpm_simulation import ScheduleMCConfig, run_schedule_mc
    from src.sra.cpm.auto_mapper import expand_auto_rules
    from src.sra.cpm.graph_builder import build_schedule_graph
    from src.sra.cpm.risk_driver_schema import AutoMapperRule
    from src.sra.cpm.xer_reader import parse_xer

    graph = build_schedule_graph(parse_xer(str(WIND_XER)))

    rules = {
        rid: AutoMapperRule(
            risk_id=rid, pattern_id=f"P{prefix}", pattern_prefixes=(prefix,),
            float_threshold_hours=480.0, injection_method="additive_pert_days",
            opt_pert=float(od), ml_pert=float(md), pess_pert=float(pd),
            probability=prob, mode=mode,
        )
        for rid, (prefix, od, md, pd, prob, mode) in _TIME_YES_RULES.items()
    }
    drivers = expand_auto_rules(rules, graph)
    assert drivers, "no risk drivers produced"
    # At least one rule bound to activities (prefixes match task_codes).
    assert any(d.affected_activity_ids for d in drivers.values())

    result = run_schedule_mc(
        graph=graph, risk_drivers=drivers,
        config=ScheduleMCConfig(n_iter=2000, batch_size=1000, seed=42, mode_multipliers=TEST_MODE_MULTIPLIERS),
    )
    finish = np.asarray(result.project_finish_hours)
    assert finish.shape[0] == 2000
    p50, p80, p90 = np.percentile(finish, [50, 80, 90])
    assert p50 > 0 and p90 >= p80 >= p50
    assert result.criticality_index  # non-empty


