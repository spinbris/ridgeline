"""Showcase-P2 WS2-C — synthetic-wind end-to-end agnosticism test.

Runs the engine on a fully non-RefProject project (the synthetic-wind
fixtures) across all three layers — cost MC, Stage 2.5 schedule MC, and
Stage 3 CPM — and asserts each completes with valid P-bands and that no
RefProject identifier reaches any output. This is the project-agnostic
regression guard: if engine code reintroduces a RefProject assumption, one
of these breaks.

Fixtures are generated by ``scripts/build_synthetic_wind_fixture.py`` and
committed under ``tests/fixtures/synthetic_wind/``.

Scope notes (engine gaps surfaced by this work, documented not worked
around):
- ``read_risks_v5`` does not read a ``Cascade_Group`` register column, so
  the cost cascade cannot be register-driven; the cascade *kernel* is
  exercised directly on wind risks here to prove it is project-agnostic.
- ``Risk_Network_Edges`` has no reader (designed, unimplemented), so
  "network edges fire" cannot be asserted through the pipeline; the
  validation helper is exercised instead.
"""
from __future__ import annotations
from tests.conftest import TEST_MODE_MULTIPLIERS

import importlib.util
from pathlib import Path

import numpy as np
import pytest

FIXTURE_DIR = Path(__file__).resolve().parent / "fixtures" / "synthetic_wind"
WIND_REGISTER = FIXTURE_DIR / "wind_register.xlsx"
WIND_XER = FIXTURE_DIR / "wind_schedule.xer"

_FORBIDDEN = ("refproject", "contractor", "r076", "r015", "r017", "r018", "r019")

# Time=Yes wind risks → (gating-activity code, opt/ml/pess days, prob, mode).
# Mirrors the 10 Time_Impact=Yes rows the P3 builder emits (Series 4 / Hybrid 4
# / Parallel 2); kept in sync with scripts/build_synthetic_wind_fixture.py. The
# prefix is the risk's single gating-activity task_code, so each rule binds
# exactly one activity (no whole-WBS-group over-binding).
_TIME_YES_RULES = {
    "WT-001": ("20.G.001", 5, 12, 24, 0.45, "Series"),
    "WT-002": ("10.G.001", 3, 7, 16, 0.50, "Hybrid"),
    "WT-008": ("30.G.001", 8, 20, 45, 0.40, "Series"),
    "WT-009": ("30.G.002", 4, 10, 24, 0.45, "Hybrid"),
    "WT-020": ("40.G.001", 1, 4, 10, 0.35, "Parallel"),
    "WT-021": ("50.G.001", 6, 15, 35, 0.30, "Series"),
    "WT-026": ("50.G.002", 2, 6, 14, 0.35, "Hybrid"),
    "WT-027": ("50.G.003", 1, 4, 10, 0.35, "Parallel"),
    "WT-031": ("60.G.001", 4, 9, 19, 0.50, "Series"),
    "WT-032": ("60.G.002", 3, 7, 16, 0.45, "Hybrid"),
}


@pytest.fixture(autouse=True)
def _wind_project(monkeypatch):
    """Activate the synthetic-wind project for every test here."""
    spec = importlib.util.spec_from_file_location(
        "wind_binding_fixture", FIXTURE_DIR / "wind_binding.py"
    )
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)  # self-registers 'synthetic_wind'
    monkeypatch.setenv("QRA_PROJECT", "synthetic_wind")


def _assert_no_refproject(text: str, context: str):
    low = text.lower()
    for token in _FORBIDDEN:
        assert token not in low, f"{context} leaks {token!r}: {text[:120]!r}"


