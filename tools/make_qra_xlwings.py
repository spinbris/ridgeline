"""QRAXL-01 step 6a - the make_xlwings analogue (the pasteable distributable).

Concatenates qra_core + its Pyodide-clean deps + the shared parser into ONE
self-contained file the user pastes into xlwings Lite. Mirrors RF-01's
make_xlwings, extended for MULTIPLE interdependent core modules: each core module
is embedded VERBATIM (base64, so byte-identical to the repo) and exec'd into
``sys.modules`` under its real dotted name in dependency order, so the modules'
own ``from src.X import Y`` imports resolve inside the single file. The xlwings
shell is appended verbatim and its ``from src.*`` imports resolve against the
bootstrapped modules.

The byte-parity gate (tests/test_qraxl01_step6a_tier1.py) asserts every embedded
core module decodes byte-identical to the repo source, so the distributable can
never drift from the engine.

Run:  python tools/make_qra_xlwings.py   ->  dist/qra_xlwings_combined.py
"""
from __future__ import annotations

import base64
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]

# Core modules, in dependency order (each imports only earlier ones + numpy/scipy).
CORE_MODULES: list[tuple[str, str]] = [
    ("src.register_contract", "src/register_contract.py"),  # REG03 S2 Validate button
    ("src.config", "src/config.py"),
    ("src.distributions", "src/distributions.py"),
    ("src.correlations", "src/correlations.py"),
    ("src.integrated.cost_dispatcher", "src/integrated/cost_dispatcher.py"),
    ("src.layer1_factors", "src/layer1_factors.py"),
    ("src.sra.mode_multipliers", "src/sra/mode_multipliers.py"),  # RS-D-3: the one Mode resolver, dependency-free
    ("src.rng_streams", "src/rng_streams.py"),  # imported by qra_core since RNGSTREAM-01; numpy only
    ("src.qra_core", "src/qra_core.py"),
    ("src.qra_register_parse", "src/qra_register_parse.py"),
    ("src.bootstrap", "src/bootstrap.py"),
    ("src.tier1_headless", "src/tier1_headless.py"),
]
SHELL = "src/tier1_xlwings_shell.py"
OUT = REPO / "dist" / "qra_xlwings_combined.py"

_BANNER = (
    "# ============================================================================\n"
    "# QRAXL-01 Tier-1 xlwings Lite combined script - GENERATED by tools/make_qra_xlwings.py\n"
    "# Do NOT edit here. Edit the src/ modules or the shell and regenerate.\n"
    "# Embedded core modules are byte-identical to the repo (byte-parity gated).\n"
    "# Pin the workbook to Pyodide 314.0.1 (ratified Q4); do not float to 314.0.2.\n"
    "# ============================================================================\n"
)

_BOOTSTRAP = '''
import sys as _sys, types as _types, base64 as _base64

def _install_core():
    for _pkg in ("src", "src.integrated", "src.sra"):
        if _pkg not in _sys.modules:
            _m = _types.ModuleType(_pkg)
            _m.__path__ = []  # mark as package
            _sys.modules[_pkg] = _m
    for _name in _ORDER:
        _mod = _types.ModuleType(_name)
        _mod.__file__ = _name.replace(".", "/") + ".py"
        _sys.modules[_name] = _mod
        exec(compile(_base64.b64decode(_MODULES[_name]), _mod.__file__, "exec"), _mod.__dict__)
        _parent, _, _leaf = _name.rpartition(".")
        if _parent:
            setattr(_sys.modules[_parent], _leaf, _mod)

_install_core()
'''


def _strip_future(text: str) -> str:
    """Drop `from __future__ import ...` lines (a single one is hoisted to the top
    of the combined file; future imports mid-file are a SyntaxError)."""
    return "".join(
        ln for ln in text.splitlines(keepends=True)
        if not ln.startswith("from __future__ import")
    )


def build(out: Path | None = None) -> Path:
    """Assemble the combined distributable. Writes to ``dist/qra_xlwings_combined.py``
    by default; pass ``out`` (e.g. a pytest ``tmp_path``) to build hermetically
    without churning the repo's ``dist/`` on every test run (GD-B byte-churn fix)."""
    out = OUT if out is None else Path(out)
    modules = {name: (REPO / rel).read_bytes() for name, rel in CORE_MODULES}
    order = [name for name, _ in CORE_MODULES]

    parts: list[str] = []
    parts.append("from __future__ import annotations\n")
    parts.append(_BANNER)
    parts.append("\n_MODULES = {\n")
    for name in order:
        b64 = base64.b64encode(modules[name]).decode("ascii")
        parts.append(f"    {name!r}: {b64!r},\n")
    parts.append("}\n")
    parts.append(f"_ORDER = {order!r}\n")
    parts.append(_BOOTSTRAP)
    parts.append(
        "\n# ============================================================================\n"
        "# xlwings Lite shell (verbatim src/tier1_xlwings_shell.py; @script entry point)\n"
        "# ============================================================================\n"
    )
    parts.append(_strip_future((REPO / SHELL).read_text(encoding="utf-8")))

    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("".join(parts), encoding="utf-8")
    return out


def embedded_core(combined_text: str) -> dict[str, bytes]:
    """Decode the embedded core modules from a built combined file (for the
    byte-parity test) - re-evaluates the `_MODULES` / `_ORDER` literals only."""
    ns: dict = {}
    for line in combined_text.splitlines():
        if line.startswith("_ORDER = "):
            exec(line, ns)
            break
    # _MODULES spans multiple lines; exec the whole dict block.
    start = combined_text.index("_MODULES = {")
    end = combined_text.index("}\n", start) + 2
    exec(combined_text[start:end], ns)
    return {name: base64.b64decode(ns["_MODULES"][name]) for name in ns["_ORDER"]}


if __name__ == "__main__":
    out = build()
    print(f"wrote {out} ({out.stat().st_size:,} bytes, {len(CORE_MODULES)} core modules embedded)")
